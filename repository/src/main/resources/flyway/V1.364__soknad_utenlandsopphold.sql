CREATE TABLE SOKNAD_UTENLANDSOPPHOLD_VURDERING
(
    ID                      BIGSERIAL PRIMARY KEY,
    SOKNADSPERIODE          DATERANGE    NOT NULL,
    LAND                    TEXT         NOT NULL,
    RESULTAT                TEXT         NOT NULL,
    GODKJENT_PERIODE        DATERANGE    NULL,
    ANTALL_GODKJENTE_DAGER  INT          NULL,
    BEGRUNNELSE             TEXT         NOT NULL,
    VURDERT_AV              TEXT         NOT NULL,
    VURDERT_TIDSPUNKT       TIMESTAMP(3) NOT NULL
);

CREATE TABLE SOKNAD_UTENLANDSOPPHOLD_GRUNNLAG
(
    ID            BIGSERIAL                              NOT NULL PRIMARY KEY,
    BEHANDLING_ID BIGINT                                 NOT NULL REFERENCES BEHANDLING (ID),
    VURDERING_ID  BIGINT                                 NOT NULL REFERENCES SOKNAD_UTENLANDSOPPHOLD_VURDERING (ID),
    AKTIV         BOOLEAN      DEFAULT TRUE              NOT NULL,
    OPPRETTET_TID TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX UIDX_SOKNAD_UTENLANDSOPPHOLD_GRUNNLAG_BEHANDLING_ID
    ON SOKNAD_UTENLANDSOPPHOLD_GRUNNLAG (BEHANDLING_ID) WHERE (AKTIV = TRUE);
