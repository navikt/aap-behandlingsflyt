    BEKREFTET_AV         TEXT         NOT NULL,
    BEKREFTET_TIDSPUNKT  TIMESTAMP(3) NOT NULL
);

CREATE TABLE BEKREFT_BREV_SENDT_GRUNNLAG
(
    ID              BIGSERIAL                              NOT NULL PRIMARY KEY,
    BEHANDLING_ID   BIGINT                                 NOT NULL REFERENCES BEHANDLING (ID),
    BEKREFTELSE_ID  BIGINT                                 NOT NULL REFERENCES BEKREFT_BREV_SENDT_BEKREFTELSE (ID),
    AKTIV           BOOLEAN      DEFAULT TRUE              NOT NULL,
    OPPRETTET_TID   TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX UIDX_BEKREFT_BREV_SENDT_GRUNNLAG_BEHANDLING_ID
    ON BEKREFT_BREV_SENDT_GRUNNLAG (BEHANDLING_ID) WHERE (AKTIV = TRUE);
